"""Generate the synthetic scenario profiles to CSV (reproducible from the seed).

Example:
    python scripts/generate_data.py --seeds 0 1 2 --out data/generated
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from energypilot.config import load_config
from energypilot.data import SCENARIOS, generate_scenario


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--seeds", type=int, nargs="+", default=[0])
    parser.add_argument("--scenarios", nargs="+", default=list(SCENARIOS))
    parser.add_argument("--out", default="data/generated")
    parser.add_argument("--config", default=None, help="TOML config (default: config/default.toml)")
    args = parser.parse_args()

    config = load_config(args.config) if args.config else load_config()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    for name in args.scenarios:
        for seed in args.seeds:
            sc = generate_scenario(name, config, seed)
            path = out / f"{name}_seed{seed}.csv"
            sc.to_frame().to_csv(path, index=False)
            meta = {
                "scenario": name,
                "seed": seed,
                "title": sc.spec.title,
                "description": sc.spec.description,
                "instruction_text": sc.spec.instruction_text,
                "instruction_issue_hour": sc.spec.instruction_issue_hour,
                "expected_outcome": sc.spec.expected_outcome,
                "ground_truth": sc.spec.ground_truth,
                "initial_soc_pct": sc.initial_soc_pct,
                "provenance": sc.provenance,
                "note": "SYNTHETIC data generated by energypilot; not measurements of a real site.",
            }
            path.with_suffix(".json").write_text(json.dumps(meta, indent=2, ensure_ascii=False))
            print(f"wrote {path}")


if __name__ == "__main__":
    main()
